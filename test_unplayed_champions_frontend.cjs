const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const context = vm.createContext({window:{addEventListener(){}},document:{addEventListener(){}}});
vm.runInContext(fs.readFileSync(require.resolve('./data.js'),'utf8'),context);
vm.runInContext(fs.readFileSync(require.resolve('./roulette-core.js'),'utf8'),context);
assert.equal(context.championDisplayName('Locke'),'Locke');
assert.equal(context.championDisplayName('Vex'),'Vex');
const instance = {scope:'ONE',requirements:{assignedPlayer:'player1',randomChampions:{player1:'Locke'},randomChampionPool:'unplayed'}};
const assignment = context.penaltyAssignmentText(instance,{player1:{displayName:'Ana'}});
assert.match(assignment,/Campeón: Locke/);
assert.match(assignment,/Campeones pendientes del álbum/);
const state = {phase:'spinning',startedAt:0,holdMs:13500,penalty:{name:'Campeón aleatorio',assignment}};
assert.equal(context.window.ShellRoulette.frame(state,0).assignment,undefined);
assert.equal(context.window.ShellRoulette.frame(state,4704).assignment,assignment);
instance.requirements.randomChampionPool='all';
assert.match(context.penaltyAssignmentText(instance),/Álbum completado: catálogo completo/);
instance.scope='BOTH';
instance.requirements.randomChampions.player2='Vex';
assert.match(context.penaltyAssignmentText(instance),/Locke.*Vex.*Álbum completado/);
instance.requirements.randomChampionPool='last_unplayed';
instance.requirements.randomChampionPoolByPlayer={player1:'unplayed',player2:'all'};
assert.match(context.penaltyAssignmentText(instance),/Locke \(último pendiente\).*Vex \(catálogo completo\)/);
delete instance.requirements.randomChampionPool;
assert.doesNotMatch(context.penaltyAssignmentText(instance),/Álbum completado|pendientes del álbum/);
console.log('Random champion presentation: Locke/Vex distinct, pool visible, hidden until roulette reveal, legacy text unchanged');
